inline const unsigned char *glyph(unsigned int cp) {
    if (cp >= 'a' && cp <= 'z') cp -= 32;
    if (cp >= 'A' && cp <= 'Z') return UPPER[cp - 'A'];
    if (cp >= '0' && cp <= '9') return DIGIT[cp - '0'];
    switch (cp) {
    case '-': return DASH;
    case '.': return DOT;
    case ':': return COLON;
    case '!': return BANG;
    case '/': return SLASH;
    case '(': return LPAR;
    case ')': return RPAR;
    case ',': return COMMA;
    case '&': return AMP;
    case '*': return STAR;
    default:  return BLANK;
    }
}

