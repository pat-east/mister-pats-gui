#!/usr/bin/env python3
"""Embeds the SVG icons of a folder into a C++ source file (a sorted table of raw SVG strings).

Usage: python3 src/ui-framework/tools/embed-icons.py <icons-folder> <output.cpp>

The SVG text is stored as it is; the framework's SVG renderer (src/ui-framework/core/Svg.h) parses it at run time, so
any SVG icon of the supported subset can be added by dropping the file into src/ui-framework/assets/bootstrap-icons.
The icons are Bootstrap Icons (MIT, see the LICENSE next to them). The table is sorted by name so the
runtime can binary-search it. The build runs this script; the output is not checked in.
"""
import os
import re
import sys

src, out = sys.argv[1], sys.argv[2]
names = sorted(f[:-4] for f in os.listdir(src) if f.endswith(".svg"))
lines = [
    "// Generated by src/ui-framework/tools/embed-icons.py from src/ui-framework/assets/bootstrap-icons. Do not edit.",
    "// Bootstrap Icons, MIT licence, Copyright (c) 2019-2024 The Bootstrap Authors.",
    '#include "ui-framework/kit/Icons.h"',
    "",
    "namespace ui {",
    "",
    "extern const IconSource kIconSources[] = {",
]
for name in names:
    if not re.fullmatch(r"[a-z0-9-]+", name):
        sys.exit("unsafe icon name: " + name)
    with open(os.path.join(src, name + ".svg"), encoding="utf-8") as handle:
        svg = handle.read().strip()
    if ')svg"' in svg:
        sys.exit("unsafe icon file: " + name)
    lines.append('    {"%s", R"svg(%s)svg"},' % (name, svg))
lines += ["};", "", "extern const int kIconSourceCount = %d;" % len(names), ""]
# The licence text travels with the icons, so a binary that contains them carries the notice.
license_path = os.path.join(src, "LICENSE")
if os.path.exists(license_path):
    with open(license_path, encoding="utf-8") as handle:
        text = handle.read().strip()
    if ')svg"' in text:
        sys.exit("unsafe licence text")
    lines += ['extern const char kBootstrapIconsLicense[] = R"svg(%s)svg";' % text, ""]
lines += ["}  // namespace ui", ""]
os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
with open(out, "w", encoding="utf-8") as handle:
    handle.write("\n".join(lines))
print("wrote %s (%d icons)" % (out, len(names)))
