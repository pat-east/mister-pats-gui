#!/usr/bin/env python3
"""Writes ScreenScraperDevLogin.cpp, with the developer login scrambled, for the build.

usage: embed-dev-login.py <env file> <output.cpp>

The env file is the git-ignored _build/screenscraper.env. Only SCREENSCRAPER_DEVID and
SCREENSCRAPER_DEVPASSWORD are read; nothing else in it ends up in the binary. When the file or
the values are missing, a stub without a login is written and the build carries on. The values
are never printed.
"""
import os
import sys


def read_env(path):
    values = {}
    try:
        with open(path, encoding="utf-8") as handle:
            for line in handle:
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                key, value = line.split("=", 1)
                value = value.strip()
                if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                    value = value[1:-1]
                values[key.strip()] = value
    except OSError:
        pass
    return values


def scramble(data, key):
    out = bytearray()
    state = 0x5A
    for i, byte in enumerate(data):
        state = (state * 33 + key[i % len(key)] + i) & 0xFF
        out.append(byte ^ state ^ key[(i * 7) % len(key)])
    return bytes(out)


def array(name, data):
    rows = []
    for i in range(0, len(data), 12):
        rows.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 12]) + ",")
    body = "\n".join(rows) if rows else "    0x00,"
    return "static const unsigned char %s[] = {\n%s\n};\n" % (name, body)


def main():
    env_path, out_path = sys.argv[1], sys.argv[2]
    values = read_env(env_path)
    dev_id = values.get("SCREENSCRAPER_DEVID", "")
    dev_password = values.get("SCREENSCRAPER_DEVPASSWORD", "")
    present = bool(dev_id and dev_password)

    head = '// Generated by tools/embed-dev-login.py. Do not edit, do not commit.\n' \
           '#include "ScreenScraperDevLogin.h"\n\nnamespace ScreenScraperDevLogin {\n\n'
    if not present:
        text = head + "bool get(std::string &, std::string &) { return false; }\n\n}\n"
    else:
        key = os.urandom(24)
        # One blob: id, a separator byte that cannot occur in text, then the password.
        blob = scramble(dev_id.encode("utf-8") + b"\x00" + dev_password.encode("utf-8"), key)
        hidden_key = bytes((b ^ 0xA5) ^ ((i * 11) & 0xFF) for i, b in enumerate(key))
        text = head + array("kBlob", blob) + "\n" + array("kKey", hidden_key) + """
bool get(std::string &devId, std::string &devPassword) {
    unsigned char key[sizeof(kKey)];
    for (unsigned i = 0; i < sizeof(kKey); ++i)
        key[i] = static_cast<unsigned char>((kKey[i] ^ ((i * 11) & 0xFF)) ^ 0xA5);
    std::string plain;
    unsigned state = 0x5A;
    for (unsigned i = 0; i < sizeof(kBlob); ++i) {
        state = (state * 33 + key[i % sizeof(key)] + i) & 0xFF;
        plain += static_cast<char>(kBlob[i] ^ state ^ key[(i * 7) % sizeof(key)]);
    }
    const size_t split = plain.find('\\0');
    if (split == std::string::npos) return false;
    devId = plain.substr(0, split);
    devPassword = plain.substr(split + 1);
    return !devId.empty() && !devPassword.empty();
}

}  // namespace ScreenScraperDevLogin
"""
    with open(out_path, "w", encoding="utf-8") as handle:
        handle.write(text)
    if present:
        print("embed-dev-login: developer login embedded")
    else:
        # Not an error: the build works, its video previews just need the login typed into the
        # settings file by hand. Loud enough to notice when preparing a release.
        sys.stderr.write("\n*** WARNING: no ScreenScraper developer login found (%s).\n"
                         "*** This binary will NOT have video previews working out of the box.\n"
                         "*** Release builds need _build/screenscraper.env.\n\n" % env_path)


if __name__ == "__main__":
    main()
